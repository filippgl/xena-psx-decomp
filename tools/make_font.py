#!/usr/bin/env python3
"""Bake a glyph atlas (ASCII + Cyrillic) from a TTF into a C header for the settings menu.
usage: make_font.py font.ttf size out.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

font_path, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
font = ImageFont.truetype(font_path, size)
chars = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0x410, 0x450)] + ["Ё", "ё", "←", "→", "●"]
ascent, descent = font.getmetrics()
cell_h = ascent + descent
glyphs = []
for ch in chars:
    l, t, r, b = font.getbbox(ch)
    adv = int(round(font.getlength(ch)))
    w = max(1, r - min(l, 0))
    img = Image.new("L", (w, cell_h), 0)
    ImageDraw.Draw(img).text((-min(l, 0), 0), ch, font=font, fill=255)
    glyphs.append((ord(ch), adv, w, img))
atlas_w = 1024
x = y = 0
rows = []
placed = []
for cp, adv, w, img in glyphs:
    if x + w > atlas_w:
        x = 0
        y += cell_h + 1
    placed.append((cp, adv, x, y, w))
    x += w + 1
atlas_h = y + cell_h
atlas = Image.new("L", (atlas_w, atlas_h), 0)
for (cp, adv, gx, gy, w), (_, _, _, img) in zip(placed, glyphs):
    atlas.paste(img, (gx, gy))
data = atlas.tobytes()
with open(out, "w", newline="\n") as f:
    f.write("/* generated by tools/make_font.py from DejaVu Sans (Bitstream Vera license) */\n#pragma once\n")
    f.write(f"#define FONT_ATLAS_W {atlas_w}\n#define FONT_ATLAS_H {atlas_h}\n#define FONT_CELL_H {cell_h}\n")
    f.write(f"#define FONT_NGLYPHS {len(placed)}\n")
    f.write("static const struct { unsigned short cp, adv, x, y, w; } font_glyphs[] = {\n")
    for cp, adv, gx, gy, w in placed:
        f.write(f"    {{{cp}, {adv}, {gx}, {gy}, {w}}},\n")
    f.write("};\nstatic const unsigned char font_atlas[] = {\n")
    for i in range(0, len(data), 32):
        f.write("    " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
    f.write("};\n")
print(len(placed), "glyphs", atlas_w, "x", atlas_h)
